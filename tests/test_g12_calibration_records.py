def test_record_round_trip_and_stats_projection() -> None:
    payload = {
        "questionId": "q01",
        "sampleKind": "g12_calibration",
        "autoDecision": "auto_escalate",
        "humanDecision": "escalate",
        "riskClass": "low",
        "domain": "physics",
        "recordedAt": "2026-08-28T01:00:00+08:00",
        "evidenceRef": "review:g12:q01",
    }
    record = G12JudgementRecord.from_dict(payload)
    assert record.sampleKind is SampleKind.G12_CALIBRATION
    assert record.to_dict() == payload
    # The stats projection is exactly the mapping calibration_stats consumes.
    matrix = build_confusion_matrix([record.stats_record()])
    assert matrix.true_positives == 1


def test_record_rejects_unknown_or_missing_fields() -> None:
    base = {
        "questionId": "q01",
        "sampleKind": "g12_calibration",
        "autoDecision": "auto_approve",
        "humanDecision": "approve",
        "riskClass": "low",
        "domain": "physics",
        "recordedAt": "2026-08-28T01:00:00+08:00",
        "evidenceRef": "review:g12:q01",
    }
    with pytest.raises(CalibrationRecordError, match="autoDecision"):
        G12JudgementRecord.from_dict({**base, "autoDecision": "maybe_auto"})
    with pytest.raises(CalibrationRecordError, match="humanDecision"):
        G12JudgementRecord.from_dict({**base, "humanDecision": "maybe_reject"})
    with pytest.raises(CalibrationRecordError, match="sampleKind"):
        G12JudgementRecord.from_dict({**base, "sampleKind": "mystery_kind"})
    for key in ("questionId", "riskClass", "domain", "recordedAt", "evidenceRef"):
        broken = {k: v for k, v in base.items() if k != key}
        with pytest.raises(CalibrationRecordError, match=key):
            G12JudgementRecord.from_dict(broken)


