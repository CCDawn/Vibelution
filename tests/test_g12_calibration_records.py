def test_bundle_complete_when_all_manifest_questions_judged() -> None:
    bundle = G12CalibrationBundle.build(manifest=_manifest(), records=_full_records())
    assert bundle.status == BUNDLE_STATUS_COMPLETE
    assert bundle.missing_question_ids() == ()
    assert bundle.manifestId == _manifest().manifestId
    assert bundle.policyId == POLICY_SNAPSHOT["policyId"]
    assert bundle.policyContentHash == POLICY_SNAPSHOT["contentHash"]


def test_bundle_pending_and_missing_projection_on_partial_collection() -> None:
    manifest = _manifest()
    bundle = G12CalibrationBundle.build(
        manifest=manifest, records=_full_records()[:11]
    )
    assert bundle.status == BUNDLE_STATUS_PENDING
    assert bundle.missing_question_ids() == ("q12",)


def test_bundle_rejects_record_outside_manifest_scope() -> None:
    with pytest.raises(CalibrationRecordError, match="sampling scope"):
        G12CalibrationBundle.build(
            manifest=_manifest(), records=[_record("q99")]
        )


def test_bundle_rejects_sample_kind_mismatch() -> None:
    with pytest.raises(CalibrationRecordError, match="sampleKind"):
        G12CalibrationBundle.build(
            manifest=_manifest(),
            records=[_record("q01", sample_kind=SampleKind.DRIFT_SENTINEL)],
        )


def test_bundle_rejects_duplicate_question_records() -> None:
    with pytest.raises(CalibrationRecordError, match="duplicate"):
        G12CalibrationBundle.build(
            manifest=_manifest(), records=[_record("q01"), _record("q01")]
        )


def test_bundle_requires_a_manifest() -> None:
    with pytest.raises(CalibrationRecordError, match="AuditSampleManifest"):
        G12CalibrationBundle.build(
            manifest="not-a-manifest",  # type: ignore[arg-type]
            records=_full_records(),
        )


def test_bundle_binds_records_to_their_own_manifest_only() -> None:
    manifest_a = _manifest()
    bundle_a = G12CalibrationBundle.build(manifest=manifest_a, records=_full_records())
    assert bundle_a.manifestId == manifest_a.manifestId
    # A different pool (chemistry instead of physics) yields a different
    # manifest hash -- the derived manifest id covers only
    # (gate, batchIndex, policy, seed, questionIds), the content hash also
    # covers strata -- and the bundle binds to that exact manifest object.
    pool_b = [
        {"questionId": entry["questionId"], "riskClass": "low", "catalogDomain": "chemistry"}
        for entry in _pool()
    ]
    manifest_c = generate_g12_calibration_manifest(
        pool=pool_b,
        policy=POLICY_SNAPSHOT,
        seed="seed-g12-records",
        generated_at="2026-08-28T00:00:00+08:00",
    )
    assert manifest_c.manifestId == manifest_a.manifestId
    assert manifest_c.manifestHash != manifest_a.manifestHash
    bound = G12CalibrationBundle.build(manifest=manifest_c, records=_full_records())
    assert bound.manifestId == manifest_c.manifestId
    assert bundle_a.records == bound.records  # same judgements, different scope


