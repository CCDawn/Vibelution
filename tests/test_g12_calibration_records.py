"""Fail-closed contract tests for G12 judgement records and bundles.

The manifest used throughout is generated by the real audit sampling
service (G12 full-pilot manifest) so the sampling-scope binding under test
is the production binding, not a hand-built stand-in.
"""

from __future__ import annotations

import pytest

from core.research.competition.calibration_records import (
    BUNDLE_STATUS_COMPLETE,
    BUNDLE_STATUS_PENDING,
    CalibrationRecordError,
    G12CalibrationBundle,
    G12JudgementRecord,
    g12_calibration_bundle_hash,
)
from core.research.competition.calibration_stats import build_confusion_matrix
from core.research.workflow.contracts.audit_sampling import SampleKind
from core.web.services.team_workflow.research_runtime.audit_sampling_service import (
    generate_g12_calibration_manifest,
)

POLICY_SNAPSHOT = {
    "policyId": "cc-auto-advance-policy-002",
    "version": "2.0.0-candidate.1",
    "contentHash": "A" * 64,
}


def _pool(count: int = 12) -> list[dict[str, str]]:
    return [
        {
            "questionId": f"q{index:02d}",
            "riskClass": "low",
            "catalogDomain": "physics",
        }
        for index in range(1, count + 1)
    ]


def _manifest(count: int = 12):
    return generate_g12_calibration_manifest(
        pool=_pool(count),
        policy=POLICY_SNAPSHOT,
        seed="seed-g12-records",
        generated_at="2026-08-28T00:00:00+08:00",
    )


def _record(
    question_id: str,
    *,
    auto: str = "auto_approve",
    human: str = "approve",
    sample_kind: SampleKind = SampleKind.G12_CALIBRATION,
) -> G12JudgementRecord:
    return G12JudgementRecord(
        questionId=question_id,
        sampleKind=sample_kind,
        autoDecision=auto,
        humanDecision=human,
        riskClass="low",
        domain="physics",
        recordedAt="2026-08-28T01:00:00+08:00",
        evidenceRef=f"review:g12:{question_id}",
    )


def _full_records(count: int = 12) -> list[G12JudgementRecord]:
    return [_record(f"q{index:02d}") for index in range(1, count + 1)]


