def test_bundle_round_trip_verifies_declared_hash_and_status() -> None:
    bundle = G12CalibrationBundle.build(
        manifest=_manifest(), records=_full_records(), bundle_id="bundle-fixed"
    )
    payload = bundle.to_dict()
    payload["bundleHash"] = g12_calibration_bundle_hash(bundle)
    restored = G12CalibrationBundle.from_dict(payload)
    assert restored.bundleId == "bundle-fixed"
    assert restored.status == BUNDLE_STATUS_COMPLETE
    assert restored.records == bundle.records
    assert restored.bundleHash == payload["bundleHash"]


def test_bundle_round_trip_rejects_tampered_hash() -> None:
    bundle = G12CalibrationBundle.build(manifest=_manifest(), records=_full_records())
    payload = bundle.to_dict()
    payload["bundleHash"] = "B" * 64
    with pytest.raises(CalibrationRecordError, match="bundleHash"):
        G12CalibrationBundle.from_dict(payload)


def test_bundle_round_trip_rejects_status_contradicting_records() -> None:
    bundle = G12CalibrationBundle.build(
        manifest=_manifest(), records=_full_records()[:6]
    )
    payload = bundle.to_dict()
    payload["status"] = BUNDLE_STATUS_COMPLETE
    with pytest.raises(CalibrationRecordError, match="status"):
        G12CalibrationBundle.from_dict(payload)


def test_bundle_round_trip_rejects_record_swapped_after_signing() -> None:
    bundle = G12CalibrationBundle.build(manifest=_manifest(), records=_full_records())
    payload = bundle.to_dict()
    payload["bundleHash"] = g12_calibration_bundle_hash(bundle)
    payload["records"][0]["humanDecision"] = "escalate"
    with pytest.raises(CalibrationRecordError, match="bundleHash"):
        G12CalibrationBundle.from_dict(payload)


