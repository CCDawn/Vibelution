export type GitRouteTranslationKey = keyof typeof gitRouteDictionary.zh;

export function useGitRouteI18n() {
  const { lang } = useShellI18n();
  const table = gitRouteDictionary[lang];
  const t = useCallback((key: GitRouteTranslationKey): string => table[key], [table]);

  return {
    lang,
    t,
  };
}

export function translateGitRoute(lang: Language, key: GitRouteTranslationKey): string {
  return gitRouteDictionary[lang][key];
}
