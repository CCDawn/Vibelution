"""Generate frontend vocabularies from their owning backend domains."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.chat.session_activity import SESSION_ACTIVITY_CONTRACT
from core.runtime_manager.agent_run_status import (
    RUN_ACTIVE_STATUSES,
    RUN_REASON_LABELS,
    RUN_STATUS_ALIASES,
    RUN_STATUS_LABELS,
    RUN_TERMINAL_STATUSES,
)

OUTPUT = ROOT / "web/src/api/generated/activityContract.ts"


def render_contract() -> str:
    payload = {
        "session": SESSION_ACTIVITY_CONTRACT,
        "agentRun": {
            "labels": RUN_STATUS_LABELS, "aliases": RUN_STATUS_ALIASES,
            "reasonLabels": RUN_REASON_LABELS,
            "activeStatuses": sorted(RUN_ACTIVE_STATUSES), "terminalStatuses": sorted(RUN_TERMINAL_STATUSES),
        },
    }
    return (
        "// Generated by scripts/generate_activity_contract.py. Edit the owning Python domain.\n"
        "export const ACTIVITY_CONTRACT = " + json.dumps(payload, ensure_ascii=False, indent=2) + " as const;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render_contract()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print("Frontend activity vocabulary is stale; run scripts/generate_activity_contract.py")
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
