"""Generate frontend vocabularies from their owning backend domains."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.chat.session_activity import SESSION_ACTIVITY_CONTRACT, SESSION_NOTIFICATION_CONTRACT
from core.runtime_manager.agent_run_status import (
    RUN_ACTIVE_STATUSES,
    RUN_REASON_LABELS,
    RUN_REASON_LABELS_EN,
    RUN_STATUS_ALIASES,
    RUN_STATUS_LABELS,
    RUN_STATUS_LABELS_EN,
    RUN_TERMINAL_STATUSES,
)

from core.runtime_manager.work_run_status import WORK_RUN_ACTIVITY_CONTRACT
from core.runtime_manager.self_observation_status import SELF_OBSERVATION_CONTRACT

OUTPUT = ROOT / "web/src/api/generated/activityContract.ts"
NATIVE_NOTIFICATION_OUTPUT = ROOT / "desktop/electron/src/notifications/conversationNotificationContract.generated.ts"
NATIVE_WORK_RUN_OUTPUT = ROOT / "desktop/electron/src/process/workRunActivityContract.generated.ts"


def render_contract() -> str:
    payload = {
        "session": SESSION_ACTIVITY_CONTRACT,
        "workRun": WORK_RUN_ACTIVITY_CONTRACT,
        "selfObservation": SELF_OBSERVATION_CONTRACT,
        "agentRun": {
            "labels": RUN_STATUS_LABELS, "aliases": RUN_STATUS_ALIASES,
            "labelsEn": RUN_STATUS_LABELS_EN,
            "reasonLabels": RUN_REASON_LABELS,
            "reasonLabelsEn": RUN_REASON_LABELS_EN,
            "activeStatuses": sorted(RUN_ACTIVE_STATUSES), "terminalStatuses": sorted(RUN_TERMINAL_STATUSES),
        },
    }
    return (
        "// Generated by scripts/generate_activity_contract.py. Edit the owning Python domain.\n"
        "export const ACTIVITY_CONTRACT = " + json.dumps(payload, ensure_ascii=False, indent=2) + " as const;\n"
    )


def render_notification_contract() -> str:
    return (
        "// Generated by scripts/generate_activity_contract.py. Edit core/chat/session_activity.py.\n"
        "export const CONVERSATION_NOTIFICATION_CONTRACT = "
        + json.dumps(SESSION_NOTIFICATION_CONTRACT, ensure_ascii=False, indent=2)
        + " as const;\n"
    )


def render_work_run_lifecycle_contract() -> str:
    payload = {
        "statusFields": WORK_RUN_ACTIVITY_CONTRACT["statusFields"],
        "resting": WORK_RUN_ACTIVITY_CONTRACT["resting"],
        "terminalStatuses": sorted(WORK_RUN_ACTIVITY_CONTRACT["outcomes"]),
    }
    return (
        "// Generated by scripts/generate_activity_contract.py. Edit core/runtime_manager/work_run_status.py.\n"
        "export const WORK_RUN_LIFECYCLE_CONTRACT = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + " as const;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        OUTPUT: render_contract(),
        NATIVE_NOTIFICATION_OUTPUT: render_notification_contract(),
        NATIVE_WORK_RUN_OUTPUT: render_work_run_lifecycle_contract(),
    }
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in outputs.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            print("Activity vocabulary is stale; run scripts/generate_activity_contract.py: " + ", ".join(stale))
        return int(bool(stale))
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
